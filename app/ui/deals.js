async function readDealsStream(resp, query) {
  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let finalPayload = null;
  while (true) {
    const { value, done } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const chunks = buffer.split("\n\n");
    buffer = chunks.pop() || "";
    for (const chunk of chunks) {
      const line = chunk.split("\n").find(l => l.startsWith("data: "));
      if (!line) continue;
      const event = JSON.parse(line.slice(6));
      if (event.event === "final") finalPayload = event.payload;
      else if (event.event === "error") throw new Error(event.message || "Search failed");
      else updateProgressEvent(event);
    }
  }
  if (finalPayload) {
    if (currentProgressEl) currentProgressEl.remove();
    renderDealsResponse(finalPayload, query);
    saveDealsHistory(query, finalPayload);
  }
}
